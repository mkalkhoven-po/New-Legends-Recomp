"""Recompiler driver.

Usage:
    python -m recompiler analyze  <default.xbe> [out.json]
    python -m recompiler generate <default.xbe> <out_dir>
    python -m recompiler dis      <default.xbe> <hex addr>...
"""
import collections
import json
import os
import sys
import time

from .analysis import Analyzer, Image
from .xbe import Xbe


def run_analysis(path, log=print):
    xbe = Xbe(open(path, "rb").read())
    img = Image(xbe)
    an = Analyzer(img)
    t = time.time()
    an.discover(xbe.entry, log=log)
    log(f"analysis: {len(an.functions)} functions, {len(an.rejected)} rejected candidates in {time.time() - t:.1f}s")
    return xbe, img, an


def cmd_analyze(path, out=None):
    xbe, img, an = run_analysis(path)
    ends = collections.Counter(b.end for f in an.functions.values() for b in f.blocks.values())
    ninsn = sum(len(b.insns) for f in an.functions.values() for b in f.blocks.values())
    tables = sum(len(f.tables) for f in an.functions.values())
    warns = [w for f in an.functions.values() for w in f.warnings]
    print(f"blocks by end kind: {dict(ends)}")
    print(f"instructions (with duplication): {ninsn}, jump tables: {tables}, warnings: {len(warns)}")
    for w in warns[:20]:
        print("  ", w)
    reasons = collections.Counter(r.split(": ", 1)[-1] for r in an.rejected.values())
    print("rejections:", reasons.most_common(8))
    if out:
        json.dump(
            {
                "entry": xbe.entry,
                "functions": {
                    f"{va:08X}": {
                        "blocks": [f"{b:08X}" for b in sorted(f.blocks)],
                        "tables": {f"{k:08X}": f"{v[0]:08X}" for k, v in f.tables.items()},
                    }
                    for va, f in sorted(an.functions.items())
                },
                "rejected": {f"{k:08X}": v for k, v in sorted(an.rejected.items())},
            },
            open(out, "w"),
            indent=1,
        )


FUNCS_PER_FILE = 300
MMIO_SECTIONS = ("D3D",)


OVERRIDES = os.path.join(os.path.dirname(__file__), "..", "config", "overrides.txt")


def load_overrides(path=OVERRIDES):
    """Guest function address -> host function name, from config/overrides.txt
    (lines of `ADDRESS name`, `#` comments)."""
    out = {}
    if os.path.exists(path):
        for line in open(path):
            line = line.split("#", 1)[0].split()
            if len(line) >= 2:
                out[int(line[0], 16)] = line[1]
    return out


def cmd_generate(path, out_dir):
    from .emit import FunctionEmitter, fname

    xbe, img, an = run_analysis(path)
    os.makedirs(out_dir, exist_ok=True)
    known = set(an.functions)
    starts = sorted(known)
    unsupported = collections.Counter()
    examples = {}
    overrides = load_overrides()
    # The XDK library that programs the GPU (NV2A) registers.
    hw = [(s["vaddr"], s["vaddr"] + s["vsize"]) for s in xbe.sections if s["name"] in MMIO_SECTIONS]

    with open(os.path.join(out_dir, "funcs.h"), "w") as f:
        f.write("// Generated by recompiler. Do not edit.\n#pragma once\n#include \"x86_recomp.h\"\n\n")
        for va in starts:
            f.write(f"void {fname(va)}(Ctx* c);\n")
        f.write("\n// Host implementations replacing guest functions (config/overrides.txt).\n")
        for va, name in sorted(overrides.items()):
            f.write(f"void {name}(Ctx* c);  // {va:08X}\n")

    files = []
    for n in range(0, len(starts), FUNCS_PER_FILE):
        name = f"code_{n // FUNCS_PER_FILE:03d}.cpp"
        files.append(name)
        parts = ['// Generated by recompiler. Do not edit.\n#include "funcs.h"\n']
        for va in starts[n : n + FUNCS_PER_FILE]:
            fe = FunctionEmitter(an.functions[va], known, overrides, mmio=any(lo <= va < hi for lo, hi in hw),
                                 eh_frame=va in an.eh_frames)
            parts.append(fe.emit())
            for addr, mn, why in fe.unsupported:
                unsupported[why] += 1
                examples.setdefault(why, addr)
        new = "\n\n".join(parts) + "\n"
        dest = os.path.join(out_dir, name)
        # Leave untouched files alone so incremental builds stay incremental.
        if not os.path.exists(dest) or open(dest).read() != new:
            open(dest, "w").write(new)

    with open(os.path.join(out_dir, "func_table.cpp"), "w") as f:
        f.write('// Generated by recompiler. Do not edit.\n#include "funcs.h"\n#include "func_table.h"\n\n')
        f.write("const FuncEntry g_func_table[] = {\n")
        table = sorted(known | set(overrides))
        for va in table:
            f.write(f"    {{0x{va:08X}u, {overrides.get(va, fname(va))}}},\n")
        f.write("};\n")
        f.write(f"const unsigned g_func_count = {len(table)};\n")
        f.write(f"const unsigned g_entry_point = 0x{xbe.entry:08X}u;\n")
    with open(os.path.join(out_dir, "sources.cmake"), "w") as f:
        f.write("set(GENERATED_SOURCES\n" + "".join(f"    ${{GENERATED_DIR}}/{n}\n" for n in files + ["func_table.cpp"]) + ")\n")

    print(f"generated {len(starts)} functions into {len(files)} files")
    print(f"unsupported instructions: {sum(unsupported.values())}")
    for why, cnt in unsupported.most_common(60):
        print(f"  {cnt:6d}  {why:<30} e.g. {examples[why]:08X}")


def cmd_dis(path, *addrs):
    """Print the blocks of the function containing each address."""
    xbe, img, an = run_analysis(path, log=lambda *_: None)
    for a in addrs:
        va = int(a, 16)
        owners = [f for f in an.functions.values() if any(
            b.insns[0].address <= va < b.insns[-1].address + b.insns[-1].size for b in f.blocks.values())]
        for f in owners[:1] or [an.explore(va)]:
            print(f"=== function {f.start:08X}")
            for b in sorted(f.blocks.values(), key=lambda b: b.start):
                print(f"  -- block {b.start:08X} end={b.end} succs={[hex(s) for s in b.succs]} target={b.target if not isinstance(b.target, int) else hex(b.target)}")
                for i in b.insns:
                    print(f"     {i.address:08X}  {i.mnemonic} {i.op_str}")


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "analyze":
        cmd_analyze(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None)
    elif len(sys.argv) >= 4 and sys.argv[1] == "generate":
        cmd_generate(sys.argv[2], sys.argv[3])
    elif len(sys.argv) >= 4 and sys.argv[1] == "dis":
        cmd_dis(sys.argv[2], *sys.argv[3:])
    else:
        print(__doc__)
        sys.exit(1)
